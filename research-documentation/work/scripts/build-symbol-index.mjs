#!/usr/bin/env node
// Generates the symbol index in <folder>/code.md and the "Anchors:" line in each component doc.
// Re-run after code changes so line numbers stay correct.
//
//   node scripts/build-symbol-index.mjs ../implementation-v2
//
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { WORK_DIR } from './lib.mjs';

const root = path.resolve(WORK_DIR, process.argv[2] ?? '../implementation-v2');
const START = '<!-- symbol-index:start -->';
const END = '<!-- symbol-index:end -->';
const A_START = '<!-- anchors:start -->';
const A_END = '<!-- anchors:end -->';

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.ts') && !e.name.endsWith('.spec.ts')) out.push(p);
  }
  return out;
}

const rel = (p) => path.relative(root, p).split(path.sep).join('/');
// Docs live beside the code (v2/v3) or mirrored under docs/code/ (v4); use whichever layout the folder has.
const DOCS_UNDER = existsSync(path.join(root, 'docs', 'code')) ? 'docs/code/' : '';
const docFor = (file) => DOCS_UNDER + file.replace(/\.ts$/, '.md');

// Route mounts from worker/src/index.ts: app.route('/api/x', xRoutes)
const mounts = {};
const indexTs = path.join(root, 'worker/src/index.ts');
if (existsSync(indexTs)) {
  for (const m of readFileSync(indexTs, 'utf8').matchAll(/app\.route\('([^']+)',\s*(\w+)\)/g)) mounts[m[2]] = m[1];
}

const files = [...walk(path.join(root, 'worker/src')), ...walk(path.join(root, 'frontend/src'))].sort();
const entries = [];
const endpoints = [];
for (const file of files) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const syms = [];
  let inClass = false;
  lines.forEach((line, i) => {
    const n = i + 1;
    let m = line.match(/^export\s+(?:default\s+)?(?:async\s+)?(function|const|class|interface|type|let)\s+(\w+)/);
    if (m) { syms.push(`${m[2]}:${n}`); inClass = m[1] === 'class'; return; }
    if (inClass && /^}/.test(line)) inClass = false;
    // Public class members (methods) at two-space indent, e.g. "  openInventory(): void {"
    // Signatures may span lines, so match only the start: "  name(" not ending in ";" or ",".
    m = inClass && !/[;,]\s*$/.test(line) && line.match(/^ {2}(?!private\b|constructor\b|if\b|for\b|while\b|switch\b|return\b)(?:async\s+)?(\w+)\s*\(/);
    if (m) syms.push(`${m[1]}():${n}`);
    // Hono handlers: xRoutes.post('/path', ...)
    m = line.match(/^(\w+Routes)\.(get|post|patch|put|delete)\('([^']*)'/);
    if (m) endpoints.push({ method: m[2].toUpperCase(), route: `${mounts[m[1]] ?? '?'}${m[3] === '/' ? '' : m[3]}`, at: `${rel(file)}:${n}`, doc: docFor(rel(file)) });
  });
  if (syms.length) entries.push({ file: rel(file), doc: docFor(rel(file)), syms });
}

// Fallback doc for files that share a parent doc (environment.prod.ts, etc.)
const docOrShared = (d) => (existsSync(path.join(root, d)) ? d : d.replace(/environment\.prod\.md$/, 'environment.md'));

let index = `${START}\n## Symbol index\n\nGenerated by \`research-documentation/work/scripts/build-symbol-index.mjs\`; don't edit by hand. Format: \`symbol:line\`. Use it instead of searching: open the doc, or view the code at that line range.\n\n### Endpoints\n\n| Method | Path | Code | Doc |\n|---|---|---|---|\n`;
for (const e of endpoints) index += `| ${e.method} | \`${e.route}\` | \`${e.at}\` | [doc](${e.doc}) |\n`;
index += `\n### Symbols by file\n\n`;
for (const e of entries) index += `- \`${e.file}\` ([doc](${docOrShared(e.doc)})): ${e.syms.map((s) => `\`${s}\``).join(', ')}\n`;
index += END;

const codeMd = path.join(root, 'code.md');
let code = readFileSync(codeMd, 'utf8');
code = code.includes(START) ? code.replace(new RegExp(`${START}[\\s\\S]*${END}`), index) : `${code.trimEnd()}\n\n${index}\n`;
writeFileSync(codeMd, code);

// Anchors line in each component doc (right after the H1 summary paragraph).
let anchored = 0;
for (const e of entries) {
  const docPath = path.join(root, docOrShared(e.doc));
  if (!existsSync(docPath)) continue;
  let doc = readFileSync(docPath, 'utf8');
  const fileName = path.basename(e.file);
  const line = `${A_START}\nAnchors (\`${fileName}\`): ${e.syms.map((s) => `\`${s}\``).join(', ')}\n${A_END}`;
  const block = new RegExp(`${A_START}\\nAnchors \\(\`${fileName.replace(/\./g, '\\.')}\`\\)[\\s\\S]*?${A_END}`);
  if (block.test(doc)) doc = doc.replace(block, line);
  else {
    // Insert before the first "## " heading.
    const at = doc.indexOf('\n## ');
    doc = at >= 0 ? `${doc.slice(0, at).trimEnd()}\n\n${line}\n${doc.slice(at)}` : `${doc.trimEnd()}\n\n${line}\n`;
  }
  writeFileSync(docPath, doc);
  anchored++;
}
console.log(`Indexed ${entries.length} files, ${endpoints.length} endpoints; anchors written to ${anchored} docs.`);
